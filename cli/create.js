function copyVendor(pkgRoot, destVendor) {
  const dist = join(pkgRoot, 'dist');
  if (!existsSync(join(dist, 'velinstyle.min.css'))) {
    return { ok: false, missing: dist };
  }
  mkdirSync(destVendor, { recursive: true });
  const files = ['velinstyle.min.css', 'velinstyle-components.min.js', 'velin-icons.svg'];
  const copied = [];
  for (const f of files) {
    const src = join(dist, f);
    if (existsSync(src)) {
      copyFileSync(src, join(destVendor, f));
      copied.push(f);
    }
  }
  const themesSrc = join(dist, 'themes');
  if (existsSync(themesSrc)) {
    cpSync(themesSrc, join(destVendor, 'themes'), { recursive: true });
    copied.push('themes/');
  }
  const docsSrc = join(pkgRoot, 'docs/generated/components');
  const mini = [
    'velin-toast.md',
    'velin-data-table.md',
    'velin-calendar.md',
    'velin-file-dropzone.md',
    'velin-stepper.md',
    'velin-search.md',
    'velin-form-summary.md',
    'velin-theme-toggle.md',
    'velin-rating.md',
  ];
  if (existsSync(docsSrc)) {
    const destDocs = join(destVendor, 'docs');
    mkdirSync(destDocs, { recursive: true });
    const indexLines = [
      '# VelinStyle WC mini-docs (offline)',
      '',
      'Copied with `velinstyle create`. Full set: framework `docs/generated/components/`.',
      'CLI: `velinstyle wc api <tag>` (e.g. `velin-toast`).',
      '',
    ];
    for (const f of mini) {
      const src = join(docsSrc, f);
      if (existsSync(src)) {
        copyFileSync(src, join(destDocs, f));
        copied.push(`docs/${f}`);
        indexLines.push(`- [${f.replace('.md', '')}](./${f})`);
      }
    }
    writeFileSync(join(destDocs, 'README.md'), `${indexLines.join('\n')}\n`, 'utf-8');
    copied.push('docs/README.md');
  }
  return { ok: copied.includes('velinstyle.min.css'), copied, destVendor };
}

/**
 * @param {{ kind: string, dir: string, pkgRoot: string, theme?: string, copyAssets?: boolean }} opts
 */
export function createProject(opts) {
  const kind = opts.kind || 'landing';
  if (!CREATE_KINDS.includes(kind)) {
    return { ok: false, error: `Unknown create kind "${kind}". Use: ${CREATE_KINDS.join('|')}` };
  }
  const dir = resolve(opts.dir || kind);
  const theme = opts.theme || (kind === 'dashboard' ? 'forest' : 'earth');
  const vendorRel = 'vendor/velinstyle';
  mkdirSync(dir, { recursive: true });

  let vendorResult = null;
  if (opts.copyAssets !== false) {
    vendorResult = copyVendor(opts.pkgRoot, join(dir, vendorRel));
    if (!vendorResult.ok) {
      return {
        ok: false,
        error: `Framework dist/ not found at ${vendorResult.missing}. Build the framework or copy dist into ${vendorRel} manually.`,
      };
    }
  }

  let html = HTML_BY_KIND[kind]({ theme, vendorPath: vendorRel });
  const check = validateBlueprintHtml(html, loadKnownCssClasses());
  if (!check.ok) {
    return { ok: false, error: `Scaffold emitted unknown classes: ${check.missing.join(', ')}` };
  }

  const indexPath = join(dir, 'index.html');
  writeFileSync(indexPath, html, 'utf-8');

  const readme = `# VelinStyle ${kind}

Created with \`velinstyle create ${kind}\`.

\`\`\`bash
velinstyle serve .
velinstyle check .
\`\`\`

Assets: \`${vendorRel}/\` · Theme: \`${theme}\`.
Offline WC notes: \`${vendorRel}/docs/\` · API: \`velinstyle wc api velin-toast\`.
Prefer \`import { bootFromDOM } from '@birdapi/velinstyle/runtime'\` in apps with the npm package.
`;
  writeFileSync(join(dir, 'README.md'), readme, 'utf-8');

  return {
    ok: true,
    kind,
    dir,
    indexPath,
    vendor: join(dir, vendorRel),
    vendorRel,
    theme,
    vendorCopied: vendorResult?.copied || [],
  };
}

/** @deprecated use createProject({ kind: 'landing', ... }) */
export function createLanding(opts) {
  return createProject({ ...opts, kind: 'landing' });
}
