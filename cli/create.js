export const CREATE_KINDS = ['landing', 'dashboard', 'docs', 'auth'];

function bootScript(vendorPath, tags) {
  const list = tags.map((t) => `'${t}'`).join(', ');
  return `  <script type="module">
    async function boot() {
      try {
        const { bootFromDOM } = await import('@birdapi/velinstyle/runtime');
        await bootFromDOM(document, {
          attributes: true,
          tags: [${list}],
        });
        return;
      } catch {
        /* offline / vendor install — no package resolver */
      }
      await import('./${vendorPath}/velinstyle-components.min.js');
    }
    boot();
  </script>`;
}

